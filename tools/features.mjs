import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 760 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await wait(500);
await page.evaluate(() => document.getElementById('btn-play').click());
await wait(200);
await page.evaluate(() => document.getElementById('btn-start').click());
await wait(4600);
const placeBefore = (kind, i) => page.evaluate(({ kind, i }) => {
  const r = window.__bb.race; const p = r.player; const t = r.track;
  const f = (kind === 'pad' ? r.features.pads : r.features.ramps)[i];
  const idx = t.wrap(f.idx - 9);
  const s = t.point(idx, f.lateral);
  p.pos.set(s.x, 0, s.z); p.heading = t.heading(idx); p.trackIdx = idx; p.trackS = idx * t.spacing;
  p.speed = 40; p.vel.set(Math.sin(p.heading) * 40, 0, Math.cos(p.heading) * 40);
  window.__bb.cam.snap = true;
}, { kind, i });
await page.keyboard.down('KeyW');
await placeBefore('pad', 2);
await wait(80);
await page.screenshot({ path: 'tools/shots/feat-pad.png' });
await wait(500);
console.log('after pad:', await page.evaluate(() => `boost=${window.__bb.race.player.boost.toFixed(2)} speed=${window.__bb.race.player.speed.toFixed(1)}`));
await placeBefore('ramp', 1);
await wait(80);
await page.screenshot({ path: 'tools/shots/feat-ramp.png' });
await wait(500);
console.log('after ramp:', await page.evaluate(() => `air=${!!window.__bb.race.player.air} y=${window.__bb.race.player.yOffset.toFixed(2)}`));
await page.screenshot({ path: 'tools/shots/feat-air.png' });
await browser.close();
