import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 800 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await wait(1500);
const measure = () => page.evaluate(() => new Promise((res) => {
  const times = []; let last = performance.now();
  const f = (now) => { times.push(now - last); last = now; if (times.length < 70) requestAnimationFrame(f); else { times.sort((a, b) => a - b); res(`median ${times[35].toFixed(1)}ms p90 ${times[63].toFixed(1)}ms max ${times[69].toFixed(1)}ms`); } };
  requestAnimationFrame(f);
}));
const p1 = measure();
await page.click('#btn-play');
await wait(250);
await page.screenshot({ path: 'tools/shots/wipe-c1.png' });
console.log('title->yard', await p1);
await wait(1200);
const p2 = measure();
await page.click('#btn-start');
console.log('yard->maps', await p2);
await browser.close();
