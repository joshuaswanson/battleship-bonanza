import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 760 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => { window.__bb.map = 'bay'; window.__bb.setup.items.splice(0, 2, 'missiles', 'armor'); });
await page.evaluate(() => document.getElementById('btn-play').click());
await wait(1500);
await page.keyboard.press('KeyO');
await wait(300);
await page.screenshot({ path: 'tools/shots/ammo-yard.png', clip: { x: 0, y: 60, width: 780, height: 420 } });
await page.evaluate(() => window.__bb.loadout && null);
await page.evaluate(() => document.getElementById('btn-start').click());
await wait(1500);
await page.evaluate(() => document.getElementById('btn-go').click());
await wait(6000);
const st = () => page.evaluate(() => { const p = window.__bb.race.player; const r = window.__bb.race; return `left=${p.charges[0].left} refill=${p.charges[0].refill.toFixed(2)} flying=${r.missiles.filter((m) => m.owner === p).length} targets=${[...new Set(r.missiles.filter((m) => m.owner === p).map((m) => m.target?.name))].join(',')} label=${document.querySelector('.ability[data-slot="0"] .slot-state').textContent}`; });
for (let i = 0; i < 4; i++) { await page.keyboard.press('KeyO'); await wait(350); console.log('press', i + 1, await st()); }
await page.screenshot({ path: 'tools/shots/ammo-hud.png' });
await wait(2500);
console.log('after 2.5s', await st());
await page.screenshot({ path: 'tools/shots/ammo-hud2.png' });
await browser.close();
