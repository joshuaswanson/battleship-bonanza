import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'], defaultViewport: { width: 1280, height: 800 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle0' });
await wait(1200);
await page.click('#btn-settings');
await wait(500);
await page.click('#toggle-music');
await wait(300);
console.log('music', await page.evaluate(() => `${window.__bb.sfx.musicOn} paused=${window.__bb.sfx.music.paused} stored=${localStorage.getItem('bb-music')}`));
await page.screenshot({ path: 'tools/shots/settings2.png' });
await page.click('#toggle-music');
await page.click('#btn-settings-close');
await page.click('#btn-play');
for (const [n, t] of [[1, 200], [2, 230], [3, 150], [4, 250], [5, 450]]) { await wait(t); await page.screenshot({ path: `tools/shots/iris-${n}.png` }); }
console.log('mode', await page.evaluate(() => !document.getElementById('screen-loadout').classList.contains('hidden')));
await browser.close();
