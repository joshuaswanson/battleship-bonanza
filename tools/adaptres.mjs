import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 760, deviceScaleFactor: 2 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
const ratio = () => page.evaluate(() => window.__bb.renderer.getPixelRatio());
await new Promise((r) => setTimeout(r, 4000));
console.log('normal ratio', await ratio());
const cdp = await page.createCDPSession();
await cdp.send('Emulation.setCPUThrottlingRate', { rate: 8 });
await new Promise((r) => setTimeout(r, 12000));
console.log('throttled ratio', await ratio());
await cdp.send('Emulation.setCPUThrottlingRate', { rate: 1 });
await new Promise((r) => setTimeout(r, 30000));
console.log('recovered ratio', await ratio());
await browser.close();
