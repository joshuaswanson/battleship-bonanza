import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 800 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle0' });
await wait(500);
await page.evaluate(() => document.getElementById('btn-play').click());
await wait(400);
const click = (id) => page.evaluate((id) => document.querySelector(`.tile[data-id="${id}"]`).click(), id);
const items = () => page.evaluate(() => JSON.stringify(window.__bb.setup.items));
const clear = () => page.evaluate(() => { for (const t of document.querySelectorAll('.tile[aria-pressed="true"]')) t.click(); });
const run = async (label, ids) => { await clear(); for (const id of ids) await click(id); console.log(label.padEnd(28), await items(), 'swap:', await page.evaluate(() => !!document.querySelector('.slot-swap'))); };
await run('jetpack', ['jetpack']);
await run('jetpack, laser', ['jetpack', 'laser']);
await run('laser, grapple', ['laser', 'grapple']);
await run('grapple, jetpack', ['grapple', 'jetpack']);
await run('jetpack, grapple', ['jetpack', 'grapple']);
await run('spikes, saw', ['spikes', 'saw']);
await run('mines, flamethrower', ['mines', 'flamethrower']);
await page.evaluate(() => document.querySelector('.slot-swap').click());
console.log('after swap'.padEnd(28), await items());
await wait(800);
await page.screenshot({ path: 'tools/shots/slots-yard.png' });
await browser.close();
