import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1440, height: 900 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'domcontentloaded' });
await wait(650);
await page.screenshot({ path: 'tools/shots/title-1.png' });
await wait(2200);
await page.screenshot({ path: 'tools/shots/title-2.png' });
await page.click('#btn-howto');
await wait(500);
await page.screenshot({ path: 'tools/shots/title-3.png' });
await browser.close();
