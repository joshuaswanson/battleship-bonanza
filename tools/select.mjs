import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1440, height: 900 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
const state = () => page.evaluate(() => `${JSON.stringify(window.__bb.setup.items)} start=${document.getElementById('btn-start').disabled ? 'disabled' : 'enabled'} name="${document.getElementById('combo-name').textContent}"`);
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await wait(500);
await page.click('#btn-play');
await wait(500);
for (const t of await page.$$('.tile[aria-pressed="true"]')) await t.click();
await wait(200);
console.log('none:', await state());
await page.screenshot({ path: 'tools/shots/sel-0.png' });
await page.click('.tile[data-id="saw"]');
await wait(200);
console.log('one:', await state());
await page.screenshot({ path: 'tools/shots/sel-1.png' });
await page.click('.tile[data-id="mines"]');
await page.click('.tile[data-id="laser"]');
await wait(200);
console.log('third blocked:', await state());
await page.click('.tile[data-id="saw"]');
await wait(200);
console.log('unselect saw:', await state());
await page.screenshot({ path: 'tools/shots/sel-2.png' });
await browser.close();
