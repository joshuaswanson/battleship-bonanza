import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 800 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle0' });
await wait(1500);
await page.screenshot({ path: 'tools/shots/s-title.png' });
await page.click('#btn-settings');
await wait(500);
await page.screenshot({ path: 'tools/shots/s-settings.png' });
await page.click('#btn-settings-close');
await page.click('#btn-play');
await wait(300);
await page.screenshot({ path: 'tools/shots/s-wipe1.png' });
await wait(250);
await page.screenshot({ path: 'tools/shots/s-wipe2.png' });
await wait(900);
await page.screenshot({ path: 'tools/shots/s-yard.png' });
console.log('start label:', await page.$eval('#btn-start', (b) => b.textContent));
await page.click('#btn-start');
await wait(1600);
await page.screenshot({ path: 'tools/shots/s-maps.png' });
await page.click('.map-card[data-map="jungle"]');
await wait(300);
console.log('map', await page.evaluate(() => window.__bb.setup.map));
await page.click('#btn-go');
await wait(2500);
console.log('mode race map', await page.evaluate(() => window.__bb.race.track.map.id));
await page.screenshot({ path: 'tools/shots/s-race.png' });
await browser.close();
