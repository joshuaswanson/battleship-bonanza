import { launch, startRace, waitForGo, wait, check } from '../lib.mjs';

const { browser, page } = await launch();
await page.evaluate(() => localStorage.removeItem('bb-hints-seen'));
await startRace(page, { map: 'bay', items: ['machinegun', 'jetpack'] });
await waitForGo(page);
await wait(800);
const hint = () => page.evaluate(() => (document.getElementById('hud-hint').classList.contains('on') ? document.getElementById('hud-hint').textContent : ''));
const first = await hint();
check('drive hint shows', /W/.test(first), first);
await page.screenshot({ path: 'tools/shots/hint-drive.png' });
await page.keyboard.down('KeyW');
await page.keyboard.down('KeyD');
await wait(1500);
await page.keyboard.up('KeyD');
await wait(1400);
const second = await hint();
check('front hint follows', /Hold O/.test(second), second);
await page.keyboard.down('KeyO');
await wait(1300);
await page.keyboard.up('KeyO');
await wait(1500);
const third = await hint();
check('back hint follows', /Tap P/.test(third), third);
await page.keyboard.press('KeyP');
await wait(1500);
check('hints finish', (await hint()) === '' && (await page.evaluate(() => localStorage.getItem('bb-hints-seen') === '1')));
await page.keyboard.up('KeyW');
await browser.close();
