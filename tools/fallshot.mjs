import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 760 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => { window.__bb.map = 'jungle'; });
await page.evaluate(() => document.getElementById('btn-play').click());
await wait(1500);
await page.evaluate(() => document.getElementById('btn-start').click());
await wait(1500);
await page.evaluate(() => document.getElementById('btn-go').click());
await wait(1500);
await page.evaluate(() => { window.__bb.autopilot = true; window.__bb.steps = 6; });
await page.waitForFunction(() => !document.getElementById('screen-results').classList.contains('hidden'), { timeout: 300000, polling: 1000 });
await page.evaluate(() => { window.__bb.steps = 1; window.__bb.autopilot = false; });
await page.click('#btn-replay');
await page.waitForFunction(() => window.__bb.cam.shot === 'falls', { timeout: 120000, polling: 100 });
for (let i = 0; i < 3; i++) { await wait(900); await page.screenshot({ path: `tools/shots/fallshot-${i}.png` }); }
await browser.close();
