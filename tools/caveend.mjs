import puppeteer from 'puppeteer-core';
const tag = process.argv[2] ?? 'a';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 760 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => { window.__bb.map = 'jungle'; });
await page.evaluate(() => document.getElementById('btn-play').click());
await wait(1400);
await page.evaluate(() => document.getElementById('btn-start').click());
await wait(1000);
await page.evaluate(() => document.getElementById('btn-go').click());
await wait(5000);
await page.evaluate(() => { document.getElementById('hud').style.display = 'none'; window.__bb.freeCam = true; });
const view = async (name, s, ahead, high) => {
  await page.evaluate(({ s, ahead, high }) => {
    const t = window.__bb.race.track; const k = Math.round(s / t.spacing) % t.N; const k2 = Math.round((s + ahead) / t.spacing) % t.N;
    const lvl = (x) => (high ? t.river.top - t.river.slope * (((x - t.river.seam) % t.length + t.length) % t.length > t.length / 2 ? ((x - t.river.seam) % t.length + t.length) % t.length - t.length : ((x - t.river.seam) % t.length + t.length) % t.length) : t.level(x, t.inTunnel(x) && t.pastSeam(x) ? 1 : 0));
    const c = window.__bb.camera; c.position.set(t.px[k], lvl(s) + 4, t.pz[k]); c.lookAt(t.px[k2], lvl(s + ahead) + 4, t.pz[k2]);
  }, { s, ahead, high });
  await wait(400);
  await page.screenshot({ path: `tools/shots/caveend-${name}-${tag}.png` });
};
const r = await page.evaluate(() => window.__bb.race.track.river);
await view('before-seam', r.seam - 70, 60, false);
await view('after-seam', r.seam + 20, 60, true);
await view('near-exit', r.tunnelOut - 30, 30, true);
await view('outside', r.tunnelOut + 50, -40, true);
await browser.close();
