import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', defaultViewport: { width: 1280, height: 800, deviceScaleFactor: 3 } });
const page = await browser.newPage();
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => localStorage.setItem('bb-music', '0'));
await page.reload({ waitUntil: 'networkidle0' });
await page.click('#btn-settings');
await new Promise((r) => setTimeout(r, 700));
const box = await (await page.$('.settings-toggles')).boundingBox();
await page.screenshot({ path: 'tools/shots/toggles.png', clip: box });
console.log(await page.evaluate(() => [...document.querySelectorAll('.toggle')].map((t) => { const a = t.getBoundingClientRect(); const k = getComputedStyle(t, '::after'); return `${a.width}x${a.height} knob ${k.width}x${k.height} top ${k.top}`; }).join(' | ')));
await page.evaluate(() => localStorage.removeItem('bb-music'));
await browser.close();
