import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--enable-precise-memory-info', '--js-flags=--expose-gc'], defaultViewport: { width: 1280, height: 760 } });
const page = await browser.newPage();
const wait = (t) => new Promise((r) => setTimeout(r, t));
const heap = (label) => page.evaluate((l) => { window.gc?.(); return `${l}: ${(performance.memory.usedJSHeapSize / 1e6).toFixed(0)}MB`; }, label).then(console.log);
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await wait(4000);
await heap('title (both maps built)');
await page.evaluate(() => { window.__bb.map = 'bay'; });
await page.evaluate(() => document.getElementById('btn-play').click());
await wait(1500);
await page.evaluate(() => document.getElementById('btn-start').click());
await wait(1500);
await page.evaluate(() => document.getElementById('btn-go').click());
await wait(2000);
await heap('race start');
await page.evaluate(() => { window.__bb.autopilot = true; window.__bb.steps = 6; });
await wait(15000);
await heap('15s of 6x sim');
await page.evaluate(() => { const r = window.__bb.recorder; r.frames.length = 0; r.events.length = 0; });
await heap('after clearing recording');
await browser.close();
