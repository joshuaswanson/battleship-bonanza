import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 760 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await page.evaluate(() => { window.__bb.map = 'bay'; });
await wait(500);
await page.evaluate(() => window.__bb.setup.items.splice(0, 2, 'saw', 'jetpack'));
await page.evaluate(() => document.getElementById('btn-play').click());
await new Promise((r) => setTimeout(r, 1400)); // PLAYWAIT
await wait(200);
await page.evaluate(() => document.getElementById('btn-start').click());
await new Promise((r) => setTimeout(r, 1400));
await page.evaluate(() => document.getElementById('btn-go').click());
await new Promise((r) => setTimeout(r, 1400));
await wait(4800);
await page.evaluate(() => {
  const r = window.__bb.race; const p = r.player;
  for (const b of r.boats) { b.ai.think = 1e9; b.ai.base = 0; b.vel.set(0, 0, 0); b.speed = 0; }
  p.ai.base = 0;
  const others = r.boats.filter((b) => !b.isPlayer);
  others.forEach((o, i) => o.pos.set(p.pos.x + 400 + i * 30, 0, p.pos.z + 400));
  const v = others[0];
  v.items = ['spikes', 'jetpack'];
  const lx = Math.cos(p.heading), lz = -Math.sin(p.heading);
  v.pos.set(p.pos.x + lx * 5.2 + Math.sin(p.heading) * 1.5, 0, p.pos.z + lz * 5.2 + Math.cos(p.heading) * 1.5);
  v.heading = p.heading; v.hp = 100; v.invuln = 0; v.lastFired = 1e9;
  window.__v = v;
});
const state = () => page.evaluate(() => { const p = window.__bb.race.player; const s = p.sawState; return `victim hp=${window.__v.hp.toFixed(0)} heat=${p.sawHeat.heat.toFixed(2)} over=${p.sawHeat.overheated} spin=${s.spin.toFixed(0)} label=${document.querySelector('.ability[data-slot="0"] .slot-state')?.textContent}`; });
await wait(1500);
console.log('released 1.5s:', await state());
await page.keyboard.down('KeyO');
await wait(1000);
console.log('held 1s:     ', await state());
await page.screenshot({ path: 'tools/shots/sawhold.png' });
await wait(2000);
console.log('held 3s:     ', await state());
await page.keyboard.up('KeyO');
await wait(1500);
console.log('released:    ', await state());
await browser.close();
