import puppeteer, { KnownDevices } from 'puppeteer-core';
import { URL, wait } from '../lib.mjs';

const device = KnownDevices[process.argv[2] ?? 'iPhone 15 Pro landscape'];
const tag = process.argv[3] ?? 'phone';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.emulate(device);
await page.goto(URL, { waitUntil: 'networkidle0' });
await wait(2500);
await page.screenshot({ path: `tools/shots/${tag}-title.png` });
const tap = async (sel) => {
  const el = await page.$(sel);
  if (!el) return console.log('missing', sel);
  await el.tap();
};
await tap('#btn-play');
await wait(1800);
await page.screenshot({ path: `tools/shots/${tag}-shipyard.png` });
await tap('#btn-start');
await wait(1800);
await page.screenshot({ path: `tools/shots/${tag}-courses.png` });
await page.evaluate(() => document.querySelector('.map-card[data-map="bay"]').click());
await tap('#btn-go');
await page.waitForFunction(() => !window.__bb.race.attract && window.__bb.race.state === 'racing', { timeout: 60000, polling: 100 });
await wait(1500);
const speed = await page.evaluate(() => window.__bb.race.player.speed);
console.log('auto throttle speed', speed.toFixed(1));
const hold = async (sel, ms) => {
  const box = await (await page.$(sel)).boundingBox();
  const x = box.x + box.width / 2;
  const y = box.y + box.height / 2;
  const cdp = await page.createCDPSession();
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
  await wait(ms);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
};
const h0 = await page.evaluate(() => window.__bb.race.player.heading);
await hold('[data-touch="left"]', 600);
console.log('steer left turned', (await page.evaluate(() => window.__bb.race.player.heading) - h0).toFixed(2));
await hold('[data-touch="item0"]', 900);
console.log('front held heat', await page.evaluate(() => window.__bb.race.player.heat.machinegun.heat.toFixed(2)));
await hold('[data-touch="item1"]', 100);
await wait(200);
console.log('back tapped jet pack air', await page.evaluate(() => !!window.__bb.race.player.air));
await hold('[data-touch="brake"]', 1200);
console.log('after brake speed', (await page.evaluate(() => window.__bb.race.player.speed)).toFixed(1));
await page.screenshot({ path: `tools/shots/${tag}-race.png` });
await browser.close();
