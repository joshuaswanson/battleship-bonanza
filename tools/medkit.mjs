import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 760 } });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const wait = (t) => new Promise((r) => setTimeout(r, t));
await page.goto('http://localhost:5288/', { waitUntil: 'networkidle0' });
await wait(500);
await page.evaluate(() => document.getElementById('btn-play').click());
await wait(200);
await page.evaluate(() => document.getElementById('btn-start').click());
await wait(4600);
await page.evaluate(() => {
  const r = window.__bb.race;
  const p = r.player;
  const kit = r.medkits.kits[0];
  const t = r.track;
  const idx = t.wrap(kit.idx - 12);
  const s = t.point(idx, kit.lateral);
  p.pos.set(s.x, 0, s.z);
  p.heading = t.heading(idx);
  p.trackIdx = idx;
  p.hp = 40;
  p.vel.set(0, 0, 0);
  window.__bb.cam.snap = true;
});
await page.screenshot({ path: 'tools/shots/kit-1.png' });
await page.keyboard.down('KeyW');
await wait(1200);
await page.keyboard.up('KeyW');
console.log(await page.evaluate(() => `hp ${window.__bb.race.player.hp}, kit cooldown ${window.__bb.race.medkits.kits[0].cooldown.toFixed(1)}`));
await page.screenshot({ path: 'tools/shots/kit-2.png' });
await browser.close();
