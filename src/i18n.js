const ACRONYMS = new Set(['emp']);

const browserLang = (navigator.language ?? 'en').slice(0, 2);
const savedLang = localStorage.getItem('bb-lang');
let lang = LANGUAGES.some((l) => l.id === savedLang) ? savedLang : LANGUAGES.some((l) => l.id === browserLang) ? browserLang : 'en';

export function getLang() {
  return lang;
}

export function setLang(id) {
  lang = id;
  localStorage.setItem('bb-lang', id);
  document.documentElement.lang = id;
}

export function t(key, vars = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof text !== 'string') return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}

export function ordinal(n) {
  if (lang === 'fr') return n === 1 ? '1er' : `${n}e`;
  if (lang === 'de') return `${n}.`;
  return `${n}${n === 1 ? 'st' : n === 2 ? 'nd' : n === 3 ? 'rd' : 'th'}`;
}

export function itemName(id) {
  return ITEM_TEXT[lang][id][0];
}

export function itemBlurb(id) {
  return ITEM_TEXT[lang][id][1];
}

export function itemInSentence(id) {
  const name = itemName(id);
  return lang === 'de' || ACRONYMS.has(id) ? name : name.toLowerCase();
}

export function comboName(items) {
  if (items.length === 0) return SOLO_NAMES[lang].none;
  if (items.length === 1) return SOLO_NAMES[lang][items[0]];
  return PAIR_NAMES[lang][[...items].sort().join('+')];
}

export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  document.documentElement.lang = lang;
}
